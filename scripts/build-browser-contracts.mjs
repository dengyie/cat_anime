import ts from 'typescript'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed })

// Translate declarative schemas at build time. Valibot owns browser parsing;
// the frozen contracts remain the sole source of fields and constraints.
export function translateSchemas(source, fileName = 'schemas.ts') {
  const input = ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true, fileName.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS)
  const result = ts.transform(input, [(context) => {
    const f = context.factory
    const call = (name, args, types) => f.createCallExpression(f.createPropertyAccessExpression(f.createIdentifier('v'), name), types, args)
    const isZ = (expression) => ts.isIdentifier(expression) && expression.text === 'z'
    const numberSchema = (node) => ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)
      && (node.expression.name.text === 'number' || numberSchema(node.expression.expression))
    const visit = (node) => {
      if (ts.isImportDeclaration(node) && node.moduleSpecifier.text === 'zod') {
        return f.createImportDeclaration(undefined, f.createImportClause(false, undefined, f.createNamespaceImport(f.createIdentifier('v'))), f.createStringLiteral('valibot'))
      }
      if (ts.isTypeReferenceNode(node) && ts.isQualifiedName(node.typeName) && isZ(node.typeName.left)) {
        const name = node.typeName.right.text
        if (name === 'infer') return f.createTypeReferenceNode('v.InferOutput', node.typeArguments?.map((arg) => ts.visitNode(arg, visit)))
        if (name === 'ZodTypeAny') return f.createTypeReferenceNode('v.GenericSchema')
        if (name === 'ZodType') return f.createTypeReferenceNode('v.GenericSchema', [f.createKeywordTypeNode(ts.SyntaxKind.UnknownKeyword), ...(node.typeArguments || [])])
      }
      if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)) {
        const method = node.expression.name.text
        const receiver = node.expression.expression
        const args = node.arguments.map((arg) => ts.visitNode(arg, visit))
        const types = node.typeArguments?.map((arg) => ts.visitNode(arg, visit))
        if (isZ(receiver)) return call(({ enum: 'picklist', discriminatedUnion: 'variant' })[method] || method, args, types)
        if (['optional', 'nullable', 'nullish', 'array'].includes(method)) return call(method, [ts.visitNode(receiver, visit), ...args])
        if (['strict', 'passthrough'].includes(method) && ts.isCallExpression(receiver)) {
          const converted = ts.visitNode(receiver, visit)
          return call(method === 'strict' ? 'strictObject' : 'looseObject', converted.arguments)
        }
        if (['min', 'max', 'int', 'positive', 'nonnegative'].includes(method)) {
          const constraint = ({ min: numberSchema(receiver) ? 'minValue' : 'minLength', max: numberSchema(receiver) ? 'maxValue' : 'maxLength', int: 'integer', positive: 'minValue', nonnegative: 'minValue' })[method]
          const constraintArgs = method === 'positive' ? [f.createNumericLiteral(1)] : method === 'nonnegative' ? [f.createNumericLiteral(0)] : args
          return call('pipe', [ts.visitNode(receiver, visit), call(constraint, constraintArgs)])
        }
        if (['parse', 'safeParse'].includes(method) && !(ts.isIdentifier(receiver) && receiver.text === 'JSON')) return call(method, [ts.visitNode(receiver, visit), ...args])
      }
      return ts.visitEachChild(node, visit, context)
    }
    return (node) => ts.visitNode(node, visit)
  }])
  const output = printer.printFile(result.transformed[0])
  result.dispose()
  return output
}

export function buildBrowserContracts({ check = false } = {}) {
  const files = ['envelope', 'jobs', 'events', 'settings']
  const body = files.map((file) => translateSchemas(readFileSync(join(root, `packages/contracts/src/${file}.ts`), 'utf8')).replace(/^import \* as v from [^\n]+\n/m, '')).join('\n')
  const output = '// Generated by scripts/build-browser-contracts.mjs from packages/contracts/src.\nimport * as v from "./browser-validation.ts";\n' + body
  const target = join(root, 'src/shared/browser-contracts.ts')
  if (check) {
    if (readFileSync(target, 'utf8') !== output) throw new Error('Browser contracts are stale; run npm run build:browser-contracts')
  } else writeFileSync(target, output)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) buildBrowserContracts({ check: process.argv.includes('--check') })
